# Audit 2026-10-19 (literal-markdown-rd): this package's roxygen does not translate
# Markdown (DESCRIPTION has no Roxygen field and no block uses @md), so Markdown in a
# roxygen block reaches the help page as typed. ?plot_prediction_deviation_panels,
# ?stepwise_pcv and ?theme_maihda showed their backticks literally, and ?theme_maihda
# the link "[ggplot2::theme_minimal()]"; ?maihda_sparse_data also lost text to
# unescaped % signs (test-audit-2026-10-19-sparse-data-rd.R). The block reads every
# page of the package tree.

# The nodes of a parsed Rd page that carry one tag. Prose is the TEXT nodes: code,
# verbatim text, equations and examples are other nodes, so R syntax in them is not
# read as Markdown.
md_rd_nodes <- function(parsed, tag) {
  out <- character()
  walk <- function(e) {
    if (identical(attr(e, "Rd_tag"), tag)) out <<- c(out, paste(unlist(e), collapse = ""))
    if (is.list(e)) for (k in e) walk(k)
  }
  walk(parsed)
  out
}

# Markdown links as roxygen writes them: [fun()], [pkg::fun()], [pkg::fun],
# [text](url) and [text][fun]. Brackets in prose such as [0, 1] do not match.
md_rd_link <- paste0(
  "\\[[A-Za-z.][A-Za-z0-9._]*(::[A-Za-z.][A-Za-z0-9._]*)?\\(\\)\\]|",
  "\\[[A-Za-z.][A-Za-z0-9._]*::[A-Za-z.][A-Za-z0-9._]*\\]|\\]\\(|\\]\\[")

test_that("no help page shows literal Markdown or loses text to an Rd comment", {
  skip_on_cran()
  rds <- sort(list.files(file.path(testthat::test_path("..", ".."), "man"),
                         pattern = "\\.Rd$", full.names = TRUE))
  # Present when the suite runs from the package tree; R CMD check copies only tests/.
  skip_if(length(rds) == 0L, "the package tree is not available")
  backtick <- star <- link <- comment <- character()
  for (rd in rds) {
    parsed <- tools::parse_Rd(rd)
    page <- sub("\\.Rd$", "", basename(rd))
    prose <- paste(md_rd_nodes(parsed, "TEXT"), collapse = "")
    if (grepl("`", prose, fixed = TRUE)) backtick <- c(backtick, page)
    if (grepl("*", prose, fixed = TRUE)) star <- c(star, page)
    if (grepl(md_rd_link, prose)) link <- c(link, page)
    # Only roxygen's header lines are Rd comments; any other one is text an
    # unescaped % cut from the page.
    comments <- md_rd_nodes(parsed, "COMMENT")
    if (!all(grepl("^% (Generated by roxygen2|Please edit documentation)", comments))) {
      comment <- c(comment, page)
    }
  }
  # A failure names the pages.
  expect_identical(paste(backtick, collapse = ", "), "")
  expect_identical(paste(star, collapse = ", "), "")
  expect_identical(paste(link, collapse = ", "), "")
  expect_identical(paste(comment, collapse = ", "), "")
})
