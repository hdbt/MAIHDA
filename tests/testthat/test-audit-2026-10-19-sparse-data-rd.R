# Audit 2026-10-19 (sparse-data-rd): ?maihda_sparse_data was written in Markdown,
# which this package's roxygen does not translate. The page showed ** and backticks
# literally, and each unescaped % began an Rd comment that dropped the rest of its
# line: "40% of the between-stratum variance" rendered as "40 between-stratum
# variance" and the binary lme4 sentence ended at "roughly 3". It also said the data
# let the vignette claim recovery of the true interaction share, which neither engine
# recovers on these data. The block reads the page from the package tree.

test_that("?maihda_sparse_data renders every line and shows no Markdown", {
  skip_on_cran()
  rd <- file.path(testthat::test_path("..", ".."), "man", "maihda_sparse_data.Rd")
  # Present when the suite runs from the package tree; R CMD check copies only tests/.
  skip_if_not(file.exists(rd), "the package tree is not available")
  parsed <- tools::parse_Rd(rd)
  comments <- character()
  walk <- function(e) {
    if (identical(attr(e, "Rd_tag"), "COMMENT")) {
      comments <<- c(comments, paste(unlist(e), collapse = ""))
    }
    if (is.list(e)) for (k in e) walk(k)
  }
  walk(parsed)
  # Only roxygen's header lines are Rd comments; any other one is text an unescaped
  # % cut from the page.
  expect_identical(
    comments[!grepl("^% (Generated by roxygen2|Please edit documentation)", comments)],
    character())
  txt <- utils::capture.output(tools::Rd2txt(rd, options = list(underline_titles = FALSE)))
  flat <- gsub("[[:space:]]+", " ", paste(txt, collapse = " "))
  expect_true(grepl("40% of the between-stratum variance", flat, fixed = TRUE))
  expect_false(grepl("**", flat, fixed = TRUE))
  expect_false(grepl("`", flat, fixed = TRUE))
  # Single-star emphasis, checked in the prose sections only: examples may hold R code.
  tags <- vapply(parsed, function(e) attr(e, "Rd_tag"), character(1))
  prose <- paste(unlist(parsed[tags %in% c("\\description", "\\details")]), collapse = "")
  expect_false(grepl("*", prose, fixed = TRUE))
  expect_false(grepl("can claim", flat, fixed = TRUE))
})
